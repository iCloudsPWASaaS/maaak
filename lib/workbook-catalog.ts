const toOptions = (items: string[]): CatalogOption[] =>
  items.map((item) => ({
    value: item,
    label: item,
    allowsCustomText: item.toLowerCase().includes("other"),
    isExclusive:
      item.toLowerCase().includes("no preference") ||
      item.toLowerCase().includes("prefer not to say") ||
      item.toLowerCase().includes("no specific diet"),
  }));

const toGroupedOptions = (groups: { group: string; items: string[] }[]): CatalogOption[] =>
  groups.flatMap((g) =>
    g.items.map((item) => ({
      value: item,
      label: item,
      group: g.group,
      allowsCustomText: item.toLowerCase().includes("other"),
    })),
  );


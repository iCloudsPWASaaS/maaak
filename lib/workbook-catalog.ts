  maxSelect?: number;
  maxLength?: number;
  isRequired: boolean;
  isPrivate?: boolean;
  supportsPreference?: boolean;
  supportsDealbreaker?: boolean;
  profileColumn?: string;
  conditionalOn?: { field: string; values: string[] };
